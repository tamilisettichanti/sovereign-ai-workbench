// Reports, Agents and Settings: simple read-only pages.
(function () {
  Pages.reports = {
    title: 'Reports',
    async render(el) {
      const draw = async () => {
        const r = await api('/api/reports');
        el.innerHTML = `
          <div class="page-head"><div><h1>Reports and Deliverables</h1><p>Word, Excel, PowerPoint and code files generated by the workbench. They are stored in <span class="mono">workspace/outputs</span>.</p></div></div>
          <div class="card">${r.files.length ? `<table class="tbl"><tr><th>File</th><th>Type</th><th>Size</th><th>Created</th><th></th></tr>
            ${r.files.map((f) => `<tr><td>${icon(extIcon(f.name), 'vertical-align:-4px;color:var(--blue)')} <b>${esc(f.name)}</b></td><td><span class="tag">${esc(f.ext.toUpperCase())}</span></td>
              <td class="muted">${f.size_kb} KB</td><td class="muted">${fmtDateTime(f.modified)}</td>
              <td style="text-align:right"><a class="btn sm" href="${fileUrl('outputs', f.name, 1)}">${icon('download')}Download</a>
              <button class="btn sm danger" data-del="${esc(f.name)}">${icon('trash')}</button></td></tr>`).join('')}</table>`
            : '<div class="empty">Nothing generated yet. Ask the AI Workbench for an approval note, a spreadsheet or a presentation.</div>'}</div>`;
        $$('[data-del]', el).forEach((b) => b.onclick = async () => {
          if (!confirm(`Delete "${b.dataset.del}"?`)) return;
          await api(`/api/file/outputs/${encodeURIComponent(b.dataset.del)}`, {method: 'DELETE'});
          draw();
        });
      };
      await draw();
    },
  };

  Pages.agents = {
    title: 'Agents',
    async render(el) {
      const d = await api('/api/agents');
      const m = await api('/api/models');
      const modelFor = (cap) => (m.models.find((x) => x.capabilities.includes(cap) && x.enabled && x.installed) || {}).label || 'no model available';
      const toolLabel = (n) => (d.tools.find((t) => t.name === n) || {}).label || n;
      el.innerHTML = `
        <div class="page-head"><div><h1>Agents</h1><p>The four flows the orchestrator can run. The router chooses the flow and its model for each request.</p></div></div>
        <div class="grid cols-4">${d.flows.map((f) => `<div class="card"><div class="row"><h4 class="grow" style="font-size:15px">${esc(f.name)}</h4><span class="pill green">Active</span></div>
          <p class="muted small" style="min-height:66px">${esc(f.description)}</p>
          <div class="kv"><span>Model</span><span>${esc(modelFor(f.capability))}</span></div>
          <div class="kv"><span>Tasks completed</span><span>${d.task_counts[f.task] || 0}</span></div>
          <div class="small muted" style="margin:8px 0 5px">TOOLS</div>${f.tools.length ? [...new Set(f.tools.map(toolLabel))].map((t) => `<span class="tag">${esc(t)}</span>`).join('') : '<span class="muted small">none</span>'}</div>`).join('')}</div>
        <div class="card mt"><h3>Agent Orchestration Workflow</h3>
          <div class="rag-flow">${[['User request', 'Message and attached files'], ['Router', 'Picks the flow and the model'], ['Plan', 'Short numbered plan'], ['Act', 'Call a tool, read the result'],
            ['Self-correct', 'Retry on tool or code errors'], ['Deliver', 'Answer and generated files']].map((s, i) => `${i ? `<span class="arrow">${icon('arrow')}</span>` : ''}<div><b>${s[0]}</b>${s[1]}</div>`).join('')}</div>
          <p class="small muted" style="margin:10px 0 0">Limits: at most ${d.limits.max_agent_steps} tool steps per task, ${d.limits.max_code_attempts} attempts to fix failing code, ${d.limits.sandbox_timeout_s} second sandbox time limit.</p></div>
        <div class="card mt"><h3>Local Tools</h3><table class="tbl"><tr><th>Tool</th><th>Function name</th><th>What it does</th></tr>
          ${d.tools.map((t) => `<tr><td><b>${esc(t.label)}</b></td><td class="mono">${esc(t.name)}</td><td class="muted">${esc(t.description)}</td></tr>`).join('')}</table></div>`;
    },
  };

  Pages.settings = {
    title: 'Settings',
    async render(el) {
      const d = await api('/api/settings');
      el.innerHTML = `
        <div class="page-head"><div><h1>Settings</h1><p>Current configuration, read from <span class="mono">workbench/config.py</span>. Change values there and restart the server.</p></div></div>
        <div class="grid cols-2">${d.settings.map((g) => `<div class="card"><h3>${esc(g.group)}</h3>
          ${g.items.map((i) => `<div class="kv"><span>${esc(i[0])}</span><span>${esc(i[1])}</span></div>`).join('')}</div>`).join('')}</div>`;
    },
  };
})();
